#!/usr/bin/env bash

###############################################################################
#
# Dock Optimization Module
#
# Optimizes:
# - Workspace
# - Responsiveness
# - Screen usage
#
###############################################################################

set -euo pipefail


log() {
    printf "[Dock] %s\n" "$1"
}


apply() {
    defaults write "$1" "$2" "-$3" "$4" 2>/dev/null || true
}


log "Configuring Dock..."


###############################################################################
# Automatically hide Dock
###############################################################################

apply com.apple.dock autohide bool true


###############################################################################
# Dock size
###############################################################################

apply com.apple.dock tilesize int 42


###############################################################################
# Disable magnification
###############################################################################

apply com.apple.dock magnification bool false


###############################################################################
# Remove show/hide delay
###############################################################################

apply com.apple.dock autohide-delay float 0


###############################################################################
# Faster hide/show animation
###############################################################################

apply com.apple.dock autohide-time-modifier float 0.15


###############################################################################
# Disable launch animation
###############################################################################

apply com.apple.dock launchanim bool false


###############################################################################
# Disable bouncing apps
###############################################################################

apply com.apple.dock no-bouncing bool true


###############################################################################
# Disable recent apps
###############################################################################

apply com.apple.dock show-recents bool false


###############################################################################
# Minimize into application icon
###############################################################################

apply com.apple.dock minimize-to-application bool true


###############################################################################
# Enable spring loading
###############################################################################

apply com.apple.dock enable-spring-load-actions-on-all-items bool true


###############################################################################
# Keep spaces stable
###############################################################################

apply com.apple.dock mru-spaces bool false


###############################################################################
# Restart Dock
###############################################################################

killall Dock 2>/dev/null || true


log "Dock optimization completed."